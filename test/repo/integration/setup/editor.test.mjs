import assert from "node:assert/strict";
import { mkdtempSync, readFileSync, rmSync } from "node:fs";
import os from "node:os";
import path from "node:path";
import test from "node:test";
import {
  configureEditor,
  describeEditorSetup,
  editorFiles,
  editorSetupPlan,
  jsonFile,
  writeGeneratedFile,
} from "../../../../scripts/setup/editor.mts";

const roots = [];

test.afterEach(() => {
  for (const root of roots.splice(0)) {
    rmSync(root, { recursive: true, force: true });
  }
});

function temporaryRoot() {
  const root = mkdtempSync(path.join(os.tmpdir(), "nwsapi-editor-"));
  roots.push(root);
  return root;
}

test("editor setup selects tsrs only where its native binary is published", () => {
  assert.equal(editorFiles("darwin", "arm64").engine, "tsrs");
  assert.equal(editorFiles("linux", "x64").engine, "tsrs");
  assert.equal(editorFiles("darwin", "x64").engine, "tsgo");
  assert.equal(editorFiles("win32", "x64").engine, "tsgo");
});

test("editor setup writes idempotent workspace settings and launchers", () => {
  const root = temporaryRoot();
  const result = configureEditor(root, "darwin", "arm64");
  assert.equal(result.engine, "tsrs");
  assert.ok(result.results.every((item) => item.status === "written"));
  assert.ok(
    configureEditor(root, "darwin", "arm64").results.every((item) => item.status === "current"),
  );
  assert.match(
    readFileSync(path.join(root, ".zed/settings.json"), "utf8"),
    /\.cache\/editor\/tsdk\/tsrs/,
  );
  assert.match(
    readFileSync(path.join(root, ".vscode/settings.json"), "utf8"),
    /js\/ts\.experimental\.useTsgo/,
  );
});

test("editor setup preserves user settings", () => {
  const root = temporaryRoot();
  writeGeneratedFile(root, ".vscode/settings.json", '{\n  "custom": true\n}\n');
  const result = configureEditor(root, "darwin", "arm64");
  assert.equal(
    result.results.find((item) => item.path === ".vscode/settings.json")?.status,
    "preserved",
  );
  assert.match(readFileSync(path.join(root, ".vscode/settings.json"), "utf8"), /"custom": true/);
  assert.match(result.messages.join("\n"), /were preserved/);
});

test("Windows editor setup selects pinned native-preview executables", () => {
  const root = temporaryRoot();
  const files = editorFiles("win32", "x64");
  assert.deepEqual(files.launchers, []);
  configureEditor(root, "win32", "x64");
  assert.match(
    readFileSync(path.join(root, ".vscode/settings.json"), "utf8"),
    /node_modules\/@typescript\/native-preview/,
  );
  assert.match(
    readFileSync(path.join(root, ".zed/settings.json"), "utf8"),
    /native-preview-win32-x64\/lib\/tsgo\.exe/,
  );
});

test("editor setup exposes descriptions and dry-run paths", () => {
  assert.equal(describeEditorSetup().name, "setup/editor");
  assert.deepEqual(editorSetupPlan("/checkout", "linux", "arm64").targets, [
    "/checkout/.cache/editor/tsdk/tsgo",
    "/checkout/.cache/editor/tsdk/tsrs",
    "/checkout/.vscode/settings.json",
    "/checkout/.vscode/extensions.json",
    "/checkout/.zed/settings.json",
  ]);
});

test("generated settings are marked JSON and custom files are unchanged", () => {
  assert.equal(
    jsonFile({ editor: true }),
    "// Generated by scripts/setup/editor.mts.\n" + '{\n  "editor": true\n}\n',
  );
});
